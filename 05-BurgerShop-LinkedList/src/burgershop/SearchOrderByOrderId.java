    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String orderId = txtOrderId.getText().trim();
        if (orderId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter an Order ID.", "Info", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        Burger b = BurgerController.getBurgerByOrderId(orderId);

        if (b == null) {
            JOptionPane.showMessageDialog(this, orderId + " order not found.");
            txtCustomerId.setText("");
            txtCustomerName.setText("");
            txtBurgerQty.setText("");
            txtOrderStatus.setText("");
            txtTotal.setText("");
        } else {
            txtCustomerId.setText(b.getCustomerId());
            txtCustomerName.setText(b.getCustomerName());
            txtBurgerQty.setText(String.valueOf(b.getQty()));
            txtOrderStatus.setText(b.getStatusString());
            txtTotal.setText(String.valueOf(b.getQty() * BurgerShop.getBurgerPrice() * 1.0));
        }

    }//GEN-LAST:event_btnSearchActionPerformed


    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String searchedCustomerId = txtCustomerID.getText().trim();
        if (searchedCustomerId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a Customer ID.", "Info", JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        List matchingOrders = BurgerController.getOrdersByCustomerId(searchedCustomerId);
        addDataToTable(matchingOrders);

        if (matchingOrders.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No orders found.", "Info", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnSearchActionPerformed


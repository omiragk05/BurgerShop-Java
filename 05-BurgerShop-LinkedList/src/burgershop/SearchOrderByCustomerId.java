    private void addDataToTable(List burgers) {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        for (int i = 0; i < burgers.size(); i++) {
            Burger b = burgers.get(i);
            double price = b.getQty() * BurgerShop.getBurgerPrice() * 1.0;
            model.addRow(new Object[]{
                b.getOrderId(),
                b.getQty(),
                price,
                b.getStatusString()
            });
        }

    }


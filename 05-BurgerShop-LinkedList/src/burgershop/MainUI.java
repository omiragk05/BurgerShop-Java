    private void scaleBurgerImage() {
        
        ImageIcon originalIcon = new ImageIcon(getClass().getResource("/burgershop/1.png"));

        
        Image scaledImage = originalIcon.getImage().getScaledInstance(
                imgBurger.getWidth(),
                imgBurger.getHeight(),
                Image.SCALE_SMOOTH
        );

      
        imgBurger.setIcon(new ImageIcon(scaledImage));
        imgBurger.setText(""); 
    }


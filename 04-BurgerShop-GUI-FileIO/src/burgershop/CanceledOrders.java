    private void btnReloadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReloadActionPerformed
        Burger[] canceledBurgerArray = new Burger[0]; 

        try (BufferedReader br = new BufferedReader(new FileReader("Burger.txt"))) {
            String line;
            while ((line = br.readLine()) != null) {
                String[] parts = line.split(",");
                if (parts.length == 5) {
                    String orderId = parts[0].trim();
                    String customerId = parts[1].trim();
                    String customerName = parts[2].trim();
                    int qty = Integer.parseInt(parts[3].trim());
                    int status = Integer.parseInt(parts[4].trim());

                    if (status == 2) { 
                        Burger b = new Burger(orderId, customerId, customerName, qty, status);
                        Burger[] tempCanceledBurgerArray = new Burger[canceledBurgerArray.length + 1];

                        for (int i = 0; i < canceledBurgerArray.length; i++) {
                            tempCanceledBurgerArray[i] = canceledBurgerArray[i];
                        }

                        tempCanceledBurgerArray[canceledBurgerArray.length] = b;

                        canceledBurgerArray = tempCanceledBurgerArray;
                    }
                }
            }
        } catch (IOException | NumberFormatException ex) {
            JOptionPane.showMessageDialog(null, "Error reading file: " + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }


        
        addDataToTable(canceledBurgerArray);
        
        
        if (canceledBurgerArray.length == 0) {
            JOptionPane.showMessageDialog(null, "No Canceled orders found.",
                    "Info", JOptionPane.INFORMATION_MESSAGE);
        }

    }//GEN-LAST:event_btnReloadActionPerformed


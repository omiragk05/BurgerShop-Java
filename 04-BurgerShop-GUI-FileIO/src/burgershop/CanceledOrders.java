    private void addDataToTable(Burger[] burgers) {
        DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
        model.setRowCount(0);

        for (Burger b : burgers) {
            double price = b.getQty() * BurgerShop.getBurgerPrice()*1.0;
            model.addRow(new Object[]{
                b.getOrderId(),
                b.getCustomerId(),
                b.getQty(),
                price
            });
        }
        
    }
    


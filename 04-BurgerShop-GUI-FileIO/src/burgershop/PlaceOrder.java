private boolean isCustomerIdValid(String customerId) {
   
    if (customerId.length() != 10) {
        return true; 
    }

 
    if (customerId.charAt(0) != '0') {
        return true; 
    }

  
    for (int i = 0; i < customerId.length(); i++) {
        if (!Character.isDigit(customerId.charAt(i))) {
            return true; 
        }
    }

    return false; 
}
    private void btnPlaceOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPlaceOrderActionPerformed
        String orderId = generateOrderId();
        String customerId = txtCustomerId.getText().trim();
        String customerName = txtCustomerName.getText().trim();
        String qtyText = txtBurgerQty.getText().trim();
        
         int qty = 0;
    try {
        qty = Integer.parseInt(qtyText);
        if (qty < 1) {
            JOptionPane.showMessageDialog(null, "Quantity must be greater than 0.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (isCustomerIdValid(customerId)){
            JOptionPane.showMessageDialog(null, "Invalid Customer ID", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (customerName.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Invalid Customer Name!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(null, "Please enter a valid number for quantity.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }


    try (BufferedWriter bw = new BufferedWriter(new FileWriter("Burger.txt", true))) {
        bw.write(orderId + ","+customerId+"," + customerName + "," + qty+","+0+"\n");
        bw.close();
        JOptionPane.showMessageDialog(null, "Order placed successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);

        // Clear fields after saving
        txtCustomerId.setText("");
        txtCustomerId.requestFocusInWindow();
        txtCustomerName.setText("");
        txtBurgerQty.setText("");
        txtTotal.setText("");
        txtOrderId.setText(generateOrderId());  // or generate next one for display

    }   catch (IOException ex) {
            Logger.getLogger(PlaceOrder.class.getName()).log(Level.SEVERE, null, ex);
        }
// TODO add your handling code here:
    }//GEN-LAST:event_btnPlaceOrderActionPerformed


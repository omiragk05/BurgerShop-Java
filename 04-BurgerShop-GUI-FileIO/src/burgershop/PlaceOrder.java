    private String generateOrderId() {
        int lastOrderIdNum = 0;
        try (BufferedReader br = new BufferedReader(new FileReader("Burger.txt"))) {
            String line;
            String lastLine = null;

            while ((line = br.readLine()) != null) {
                lastLine = line;
            }

            if (lastLine != null && lastLine.length() >= 5) {
                lastOrderIdNum = Integer.parseInt(lastLine.substring(1, 5));
            }

        } catch (IOException ex) {

        }

        return String.format("B%04d", lastOrderIdNum + 1);
    }


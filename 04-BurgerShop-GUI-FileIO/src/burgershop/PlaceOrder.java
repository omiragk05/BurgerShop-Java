    private void btnCalculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalculateActionPerformed
        if (txtBurgerQty.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please enter a quantity.", "Error", JOptionPane.ERROR_MESSAGE);
        } else {
            int qty = Integer.parseInt(txtBurgerQty.getText().trim());
            if (qty < 1) {
                JOptionPane.showMessageDialog(null, "Quantity must be at least 1.", "Error", JOptionPane.ERROR_MESSAGE);
            } else {
                double Price = qty * BurgerShop.getBurgerPrice() * 1.0;
                txtTotal.setText(String.valueOf(Price));
            }
        }// TODO add your handling code here:
    }//GEN-LAST:event_btnCalculateActionPerformed


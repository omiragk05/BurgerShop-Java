    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String orderId = txtOrderId.getText();
        editingOrderId = orderId;
        try {
            BufferedReader br = new BufferedReader(new FileReader("Burger.txt"));
            String line = br.readLine();
            while (line != null) {
                if (line.substring(0, 5).equals(orderId)) {
                    break;

                }
                line = br.readLine();
            }

            br.close();
            if (line == null) {
                txtCustomerId.setText("");
                txtCustomerName.setText("");
                txtBurgerQty.setText("");
                comboBox.setSelectedIndex(0);
                txtBurgerQty.setEditable(false);
                btnSave.setVisible(false);
                JOptionPane.showMessageDialog(this, orderId + " order not found.");

            } else {
                String[] rowData = line.split(",");
                txtCustomerId.setText(rowData[1]);
                txtCustomerName.setText(rowData[2]);
                txtBurgerQty.setText(rowData[3]);
                comboBox.setSelectedIndex(Integer.parseInt(rowData[4]));
                int orderStatus = Integer.parseInt(rowData[4]);

                if (orderStatus == 0) {
                    txtBurgerQty.setEditable(true);
                    btnSave.setVisible(true);
                } else {
                    txtBurgerQty.setEditable(false);
                    comboBox.setFocusable(false);
                    btnSave.setVisible(false);
                    JOptionPane.showMessageDialog(this, orderId + " can not be updated.\nOnly Peparing orders can be updated. ");
                }

            }
        } catch (IOException ex) {

        }

    }//GEN-LAST:event_btnSearchActionPerformed


    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

        String orderId = editingOrderId;
        String customerId = txtCustomerId.getText();
        String customerName = txtCustomerName.getText();
        String orderQty = txtBurgerQty.getText();
        int orderStatus = comboBox.getSelectedIndex();

        try {
            Scanner input = new Scanner(new File("Burger.txt"));
            FileWriter tempWriter = new FileWriter(new File("TempBurger.txt"));

            while (input.hasNextLine()) {
                String line = input.nextLine();
                if (line.substring(0, 5).equals(orderId)) {
                    tempWriter.write(orderId + "," + customerId + "," + customerName + "," + orderQty + "," + orderStatus + "\n");
                } else {
                    tempWriter.write(line + "\n");
                }
            }
            input.close();
            tempWriter.close();

            new File("Burger.txt").delete();
            Scanner tempInput = new Scanner(new File("TempBurger.txt"));
            FileWriter newFile = new FileWriter("Burger.txt");

            while (tempInput.hasNextLine()) {
                newFile.write(tempInput.nextLine() + "\n");
            }

            newFile.close();
            tempInput.close();

            new File("TempBurger.txt").delete();
            JOptionPane.showMessageDialog(this, orderId + " has been updated.\nOrder Qty : " + orderQty + "\nOrder Status : "+getStatusString(orderStatus));
            txtBurgerQty.setEditable(false);
            comboBox.setFocusable(false);
            btnSave.setVisible(false);
            

        } catch (IOException ex) {
            System.err.println("Error processing files: " + ex.getMessage());
            ex.printStackTrace();
        }

// TODO add your handling code here:
    }//GEN-LAST:event_btnSaveActionPerformed
    public String getStatusString(int status ) {
       if(status==0){
           return "Preparing";
       }else if(status==1){
           return "Deliverded";
       }else{
           return "Canceled";
       }
    }
